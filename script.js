let app = {
    start: function() {
      let questionSetsBtns = document.querySelectorAll(".questionSets");
        questionSetsBtns.forEach((element, index) => {
            element.textContent = questionSets[index].questionSetTitle;
            element.addEventListener("click", () => { 
                window.location.href = `${questionSets[index].questionSetTitle.toLowerCase().replaceAll(" ","_")}.html`;
            });
        });  
    },
    startQuiz: function() {
        let selection = window.location.pathname.replaceAll("/","").replaceAll(".html","");
        let selectedQuestions = questionSets.filter((x) => {return x.questionSetTitle.toLowerCase() == selection.toLowerCase().replaceAll("_"," ")})[0].questions.sort ( ( ) => Math . random ( ) - 0.5 );
        this.currentPosition = 0;
        this.score = 0;
        let ans = document.querySelectorAll(".answer");
        ans.forEach((element, index) => {
            element.addEventListener("click", () => {
                this.checkAnswer(index, selectedQuestions);
            });
        });
        this.updateStats();
        this.showQuestion(selectedQuestions[this.currentPosition]);
    },
    showQuestion: function(q) {
        let titleDiv = document.getElementById("title");
        titleDiv.textContent = q.title;
        let ans = document.querySelectorAll(".answer");
        ans.forEach(function(element, index) {
            element.textContent = q.answers[index];
        });
    },
    checkAnswer: function(userSelected, questions) {
        let currentQuestion = questions[this.currentPosition];
        if(currentQuestion.correctAnswer == userSelected) {
            console.log("Correct Answer!")
            this.score++;
            this.showResult(true, questions);
        }
        else {
            console.log("Incorrect Answer!")
            this.showResult(false, questions);
        }
        this.updateStats();
        this.increasePosition(questions);
        this.showQuestion(questions[this.currentPosition]);
    },
    increasePosition: function(questions) {
        this.currentPosition++;
        if(this.currentPosition == questions.length) {
            this.currentPosition = 0;
        }
    },
    updateStats: function() {
        let scoreDiv = document.getElementById("score");
        scoreDiv.textContent = `Your Score: ${this.score}`;
    },
    showResult: function(isCorrect, questions) {
        let resultDiv = document.getElementById("result");
        let result = "";
        if (isCorrect) {
            result = "Correct Answer!";
        } else {
            let currentQuestion = questions[this.currentPosition];
            let correctAnswIndex = currentQuestion.correctAnswer;
            let correctAnswText = currentQuestion.answers[correctAnswIndex];
            result = `Incorrect Answer! Correct Answer: ${correctAnswText}`;
        }
        resultDiv.textContent = result;
    }
};

if (window.location.pathname == "/index.html") {
    app.start();
} else {
    app.startQuiz();
}

